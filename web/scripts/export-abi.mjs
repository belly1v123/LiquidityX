#!/usr/bin/env node
// Exports contract ABIs from contracts/out into web/lib/abi/*.ts and copies
// contracts/deployments/*.json into web/lib/deployments/.
// Implementation artifacts are preferred; the frozen interface artifact is the fallback.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "..");
const root = resolve(web, "..");
const out = join(root, "contracts", "out");
const abiDir = join(web, "lib", "abi");
const depSrc = join(root, "contracts", "deployments");
const depDst = join(web, "lib", "deployments");

const CONTRACTS = [
  ["PriceOracleAdapter", "priceOracleAdapterAbi", "priceOracleAdapter"],
  ["ProtocolConfig", "protocolConfigAbi", "protocolConfig"],
  ["LiquidityXVault", "liquidityXVaultAbi", "liquidityXVault"],
  ["CollateralManager", "collateralManagerAbi", "collateralManager"],
  ["LoanManager", "loanManagerAbi", "loanManager"],
  ["LoanMarketplace", "loanMarketplaceAbi", "loanMarketplace"],
  ["LiquidationEngine", "liquidationEngineAbi", "liquidationEngine"],
];

mkdirSync(abiDir, { recursive: true });
mkdirSync(depDst, { recursive: true });

const header = "// Generated by web/scripts/export-abi.mjs. Do not edit by hand; run `pnpm --dir web abi`.\n";
const index = [header];

for (const [name, constName, file] of CONTRACTS) {
  const impl = join(out, `${name}.sol`, `${name}.json`);
  const iface = join(out, "ILiquidityX.sol", `I${name}.json`);
  const src = existsSync(impl) ? impl : existsSync(iface) ? iface : null;
  if (!src) {
    console.error(`missing artifact for ${name} (looked at ${impl} and ${iface}); run forge build in contracts/`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(src, "utf8"));
  const from = src === impl ? "implementation" : "interface";
  writeFileSync(
    join(abiDir, `${file}.ts`),
    `${header}// Source: ${src.slice(root.length + 1)} (${from})\nexport const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${constName} } from "./${file}";`);
  console.log(`${constName.padEnd(24)} <- ${from} (${abi.length} entries)`);
}

writeFileSync(join(abiDir, "erc20.ts"), `${header}export { erc20Abi } from "viem";\n`);
index.push(`export { erc20Abi } from "./erc20";`);
writeFileSync(join(abiDir, "index.ts"), index.join("\n") + "\n");

// Deployments: copy JSON files and write a static index so they bundle (Vercel) and a
// missing file never breaks the build.
const chainFiles = [];
if (existsSync(depSrc)) {
  for (const f of readdirSync(depSrc)) {
    if (!/^\d+\.json$/.test(f)) continue;
    copyFileSync(join(depSrc, f), join(depDst, f));
  }
}
for (const f of readdirSync(depDst)) if (/^\d+\.json$/.test(f)) chainFiles.push(f);
const depIndex = [header.trim()];
for (const f of chainFiles) depIndex.push(`import d${f.replace(".json", "")} from "./${f}";`);
depIndex.push(
  "",
  "/** Raw deployment JSON by chain id (shape written by contracts/script/Deploy.s.sol). */",
  "export const rawDeployments: Record<number, unknown> = {",
  ...chainFiles.map((f) => `  ${f.replace(".json", "")}: d${f.replace(".json", "")},`),
  "};",
  "",
);
writeFileSync(join(depDst, "index.ts"), depIndex.join("\n"));
console.log(`deployments: ${chainFiles.length ? chainFiles.join(", ") : "none"}`);
